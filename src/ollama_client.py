

import json
import re
import requests


SYSTEM_PROMPT = """
Ты — эксперт по проверке качества описаний вакансий.

Твоя задача — находить только реальные проблемы, которые мешают
соискателю понять условия работы.

ОБЯЗАТЕЛЬНЫЕ ПРАВИЛА:

1. Анализируй только факты из предоставленной вакансии.
2. Никогда не придумывай отсутствующие требования, обязанности,
   условия труда или нарушения законодательства.
3. Не считай отсутствие требования к образованию проблемой.
   Работодатель не обязан указывать образование, если оно не требуется.
4. Не считай experience = 0 отсутствием информации.
   Это означает, что опыт работы не требуется.
5. Не считай фразы "Полный рабочий день" или "Полная занятость"
   ошибкой сами по себе.
6. Не считай отсутствие максимальной зарплаты противоречием,
   если указана только минимальная зарплата.
   Это может быть неполнотой информации.
7. Если зарплата равна нулю или не указана, можно отметить
   отсутствие информации об оплате. Не создавай отдельные замечания
   для salary_min и salary_max по одной и той же причине.
8. Не требуй перечислять конкретные программы, если в вакансии
   просто указано владение офисными программами.
   Отмечай это только если отсутствие конкретики действительно
   мешает понять требование.
9. Не ищи нарушения закона, если в исходных данных нет
   конкретных признаков такого нарушения.
10. Не повторяй одну проблему разными словами.
11. Не считай общие формулировки противоречиями.
12. Если проблема уже очевидно описана в структурированных полях,
    не создавай искусственное замечание о её отсутствии.

ПРОВЕРЯЙ:
- понятность обязанностей;
- конкретность требований;
- неоднозначность условий труда;
- противоречия между разными полями;
- непонятный формат работы;
- неполную информацию об оплате и графике.

Для каждого замечания:
- topic — краткое название проблемы;
- source_field — точное название исходного поля;
- quote — дословная цитата из вакансии;
- problem — объяснение проблемы;
- recommendation — конкретный способ исправления.

Не добавляй замечания, если реальной проблемы нет.

Верни ТОЛЬКО JSON:
{
  "issues": [
    {
      "topic": "...",
      "source_field": "...",
      "quote": "...",
      "problem": "...",
      "recommendation": "..."
    }
  ]
}

Если проблем нет, верни:
{"issues": []}
"""


def ask_ollama(vacancy, config):
    base_url = config.get(
        "base_url",
        "http://localhost:11434"
    ).rstrip("/")

    model = config.get("model", "qwen2.5:3b")

    prompt_data = json.dumps(
        vacancy,
        ensure_ascii=False,
        default=str
    )

    prompt = (
        "Проверь понятность условий этой вакансии. "
        "Используй только факты из её полей. "
        "Не придумывай проблемы и не дублируй одну проблему. "
        "Если существенных замечаний нет, верни пустой список.\n\n"
        "ВАКАНСИЯ:\n"
        + prompt_data
    )

    response = requests.post(
        f"{base_url}/api/chat",
        json={
            "model": model,
            "stream": False,
            "format": "json",
            "messages": [
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            "options": {
                "temperature": 0.0
            }
        },
        timeout=config.get("timeout", 180)
    )

    response.raise_for_status()

    content = response.json().get(
        "message", {}
    ).get("content", "")

    try:
        parsed = json.loads(content)

    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", content, flags=re.S)

        if not match:
            raise ValueError(
                "Ollama вернула ответ не в формате JSON"
            )

        parsed = json.loads(match.group(0))

    issues = parsed.get("issues", [])

    if not isinstance(issues, list):
        return []

    return [
        issue
        for issue in issues
        if isinstance(issue, dict)
        and all(
            isinstance(issue.get(field), str)
            for field in (
                "topic",
                "source_field",
                "quote",
                "problem",
                "recommendation"
            )
        )
    ]
